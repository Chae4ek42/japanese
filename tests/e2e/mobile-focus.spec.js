import { test } from '@playwright/test'
import { expect, mockAccountsApi, swipeTouch } from './helpers.js'

async function openPractice(page) {
  await mockAccountsApi(page)
  await page.addInitScript(() => {
    if (sessionStorage.getItem('focus-seeded')) return
    sessionStorage.setItem('focus-seeded', '1')
    localStorage.clear()
    localStorage.setItem('jp-account-session-v1', JSON.stringify({ token: 'e2e-token', accountId: 'acc_e2e_default', expiresAt: Date.now() + 86400000 }))
    const customWords = Object.fromEntries(Array.from({ length: 90 }, (_, i) => [`custom:focus${i}`, {
      id: `custom:focus${i}`, writing: `言葉${i}`, kana: 'ことば', romaji: `kotoba${i}`, meanings: [`слово ${i}`, `дополнительное значение ${i}`], kanji: [],
    }]))
    const stats = Object.fromEntries(Object.keys(customWords).slice(0, 5).map((id) => [id, {
      exposures: 5, clears: 0, errors: 5, hints: 0, streak: 0, bestStreak: 0, mastery: .1,
      avgLatencyMs: 0, fastestLatencyMs: 0, lastSeenAt: 0, lastClearAt: 0, lastErrorAt: 0, lastHintAt: 0,
      eventAccuracy: 0, recentAnswers: Array(5).fill('wrong'),
    }]))
    localStorage.setItem('jp-state-draft-v1:acc_e2e_default', JSON.stringify({ version: 32, vocab: {
      myWords: Object.keys(customWords), customWords, stats, trainingSessions: [],
    } }))
  })
  await page.goto('/train', { waitUntil: 'domcontentloaded' })
  await page.getByTestId('new-vocab-session').click()
  await page.getByTestId('vocab-session-mode-adaptive').click()
  await page.getByTestId('start-vocab').click()
  await expect(page.getByTestId('vocab-current-writing')).toBeVisible()
}

test('mobile practice occupies the viewport and locks page scrolling, then restores the app on exit', async ({ page, isMobile }, testInfo) => {
  test.skip(!isMobile, 'Isolated mobile practice.')
  await openPractice(page)
  await expect(page.locator('.site-header')).toBeHidden()
  await expect(page.getByTestId('vocab-sessions-back')).toBeHidden()
  for (const size of [{ width: 393, height: 727 }, { width: 320, height: 568 }, { width: 740, height: 360 }]) {
    await page.setViewportSize(size)
    const bounds = await page.locator('.vocab-practice').boundingBox()
    expect(bounds).toEqual({ x: 0, y: 0, ...size })
    for (const id of ['vocab-practice-exit', 'vocab-open-words', 'vocab-hint-button', 'vocab-remember', 'vocab-dont-know']) await expect(page.getByTestId(id)).toBeInViewport()
    await page.evaluate(() => window.scrollTo(0, 800))
    expect(await page.evaluate(() => window.scrollY)).toBe(0)
  }
  await page.setViewportSize({ width: 393, height: 727 })
  const first = await page.getByTestId('vocab-current-writing').innerText()
  await swipeTouch(page, page.getByTestId('vocab-current-writing'), { dx: 0, dy: -110 })
  await expect(page.getByTestId('vocab-current-writing')).not.toHaveText(first)
  await expect(page.getByTestId('session-chips').locator('.session-chip').first()).toHaveText('1 карточка')
  expect(await page.evaluate(() => window.scrollY)).toBe(0)
  const next = await page.getByTestId('vocab-current-writing').innerText()
  await page.screenshot({ path: testInfo.outputPath('focus-card.png'), scale: 'css' })
  await page.getByTestId('vocab-practice-exit').tap()
  await expect(page.getByTestId('new-vocab-session')).toBeVisible()
  await expect(page.locator('.site-header')).toBeVisible()
  expect(await page.evaluate(() => document.body.style.position)).not.toBe('fixed')
  await page.getByRole('button', { name: 'Продолжить', exact: true }).click()
  await expect(page.getByTestId('vocab-current-writing')).toHaveText(next)
})

test('word sheet searches, filters, expands, excludes, restores and scrolls independently of the card', async ({ page, isMobile }, testInfo) => {
  test.skip(!isMobile, 'Mobile word sheet.')
  await openPractice(page)
  const writing = page.getByTestId('vocab-current-writing')
  const first = await writing.innerText()
  const sheet = page.getByTestId('vocab-words-sheet')
  await page.getByTestId('vocab-open-words').tap()
  await expect(sheet).toBeVisible()
  await expect(page.getByTestId('vocab-words-close')).toBeFocused()
  await expect(page.locator('input:focus')).toHaveCount(0)
  const rows = sheet.locator('.mobile-session-word')
  await expect(rows).toHaveCount(50)
  await sheet.evaluate((node) => Promise.all(node.getAnimations().map((animation) => animation.finished)))
  await page.screenshot({ path: testInfo.outputPath('focus-word-list.png'), scale: 'css' })
  await page.getByTestId('vocab-session-filter-active').tap()
  await expect(rows).toHaveCount(5)
  await page.getByTestId('vocab-session-filter-problem').tap()
  await expect(rows).toHaveCount(5)
  await page.getByTestId('vocab-session-filter-all').tap()
  await page.getByTestId('vocab-session-search').fill('kotoba12')
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('Space')
  await expect(writing).toHaveText(first)
  await expect(page.getByTestId('vocab-hint-panel')).toHaveCount(0)
  await expect(rows).toHaveCount(1)
  await rows.first().locator('.mobile-session-word-main').tap()
  await expect(rows.first().locator('.mobile-session-word-details')).toContainText('дополнительное значение 12')
  await expect(rows.first().locator('.mobile-session-word-details')).toContainText('ことば')
  await page.getByTestId('vocab-session-exclude-custom:focus12').tap()
  await expect(page.getByTestId('vocab-session-restore-custom:focus12')).toBeVisible()
  await page.getByTestId('vocab-session-search').fill('')
  await page.getByTestId('vocab-session-filter-excluded').tap()
  await expect(rows).toHaveCount(1)
  await page.getByTestId('vocab-session-restore-all').tap()
  await expect(rows).toHaveCount(0)
  await page.getByTestId('vocab-session-filter-all').tap()
  await swipeTouch(page, rows.first().locator('.mobile-session-word-main'), { dx: 0, dy: -130 })
  expect(await page.getByTestId('vocab-session-scroll').evaluate((node) => node.scrollTop)).toBeGreaterThan(0)
  expect(await page.evaluate(() => window.scrollY)).toBe(0)
  await expect(writing).toHaveText(first)
  await expect(page.getByTestId('session-chips').locator('.session-chip').first()).toHaveText('0 карточек')
  await page.getByRole('button', { name: 'Показать ещё 40', exact: true }).click()
  await expect(rows).toHaveCount(90)
  await page.getByTestId('vocab-session-current-filter').tap()
  await expect(rows).toHaveCount(1)
  await expect(rows.first()).toHaveClass(/is-current/)
  await page.screenshot({ path: testInfo.outputPath('focus-word-sheet.png'), scale: 'css' })
  await page.keyboard.press('Escape')
  await expect(sheet).toBeHidden()
  await expect(page.getByTestId('vocab-open-words')).toBeFocused()
  await expect(writing).toHaveText(first)
  await page.getByTestId('vocab-open-words').tap()
  await page.mouse.click(10, 10)
  await expect(sheet).toBeHidden()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.getByTestId('vocab-open-words').tap()
  await swipeTouch(page, sheet.locator('.vocab-sheet-handle'), { dx: 0, dy: 130 })
  await expect(sheet).toBeHidden()
})
