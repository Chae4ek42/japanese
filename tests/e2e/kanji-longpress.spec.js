import { test } from '@playwright/test'
import { expect, openFreshApp } from './helpers.js'

test('mobile tap opens kanji sheet, words and training without a keyboard', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'mobile-chrome', 'Mobile-only kanji sheet.')
  await openFreshApp(page)
  await page.getByTestId('nav-kanji').click()
  await expect(page.getByTestId('kanji-page')).toBeVisible()

  await page.getByTestId('kanji-cell-日').tap()
  await expect(page.getByTestId('kanji-info-card')).toBeVisible()
  await expect(page.getByTestId('kanji-info-card')).toContainText('N5')
  await expect(page.getByTestId('kanji-trainer')).toHaveCount(0)
  await expect(page.getByRole('tab', { name: 'Знак', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByTestId('kanji-info-words')).toBeHidden()
  await expect(page.locator('#root')).toHaveAttribute('inert', '')
  await page.getByTestId('kanji-info-toggle-learned').tap()
  await expect(page.getByTestId('kanji-info-toggle-learned')).toHaveAttribute('aria-pressed', 'true')

  await page.getByTestId('kanji-info-tab-words').tap()
  const trainButton = page.locator('[data-testid^="kanji-info-train-word-"]').first()
  await trainButton.tap()
  await expect(trainButton).toHaveAttribute('aria-pressed', 'true')
  const saveButton = page.locator('[data-testid^="kanji-info-save-word-"]').first()
  await saveButton.tap()
  await expect(saveButton).toHaveAttribute('aria-pressed', 'true')
  await saveButton.tap()
  await expect(saveButton).toHaveAttribute('aria-pressed', 'false')

  const body = page.getByTestId('kanji-info-body')
  await body.evaluate((element) => { element.scrollTop = 350 })
  const wordsScroll = await body.evaluate((element) => element.scrollTop)
  expect(wordsScroll).toBeGreaterThan(0)
  await page.getByTestId('kanji-info-tab-overview').tap()
  await page.getByTestId('kanji-info-tab-words').tap()
  await expect.poll(() => body.evaluate((element) => element.scrollTop)).toBe(wordsScroll)
  await expect(page.getByTestId('kanji-info-close')).toBeInViewport()
  await expect(page.getByTestId('kanji-info-practice')).toBeInViewport()

  await page.getByTestId('kanji-info-practice').tap()
  await expect(page.getByTestId('kanji-trainer')).toBeVisible()
  await expect(page.locator('#root')).not.toHaveAttribute('inert')

  const glyph = page.getByTestId('kanji-focus-char')
  await glyph.scrollIntoViewIfNeeded()
  await glyph.tap()
  await expect(page.getByTestId('kanji-info-card')).toBeVisible()
  await page.getByTestId('kanji-info-close').click()

  await glyph.scrollIntoViewIfNeeded()
  await glyph.click({ delay: 600 })
  await expect(page.getByTestId('kanji-info-card')).toBeVisible()
  await page.getByTestId('kanji-info-close').tap()

  await page.getByTestId('nav-home').click()
  await page.getByTestId('open-vocab-train').click()
  await page.getByTestId('vocab-source-group').click()
  await page.getByTestId('vocab-train-group-weekdays').click()
  await page.getByTestId('start-vocab').click()
  const writing = await page.getByTestId('vocab-current-writing').innerText()
  await page.locator('[data-testid="vocab-current-writing"] [data-kanji-chip]').first().tap()
  await expect(page.getByTestId('kanji-info-card')).toBeVisible()
  await page.getByTestId('kanji-info-tab-overview').focus()
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('Space')
  await expect(page.getByTestId('kanji-info-tab-composition')).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByTestId('vocab-current-writing')).toHaveText(writing)
  await expect(page.getByTestId('vocab-hint-panel')).toHaveCount(0)
  await page.getByTestId('kanji-info-done').tap()
  await expect(page.getByTestId('kanji-info-card')).toHaveCount(0)
  await expect(page.getByTestId('vocab-current-writing')).toHaveText(writing)
  await expect(page.locator('input:focus, textarea:focus')).toHaveCount(0)
})

test('mobile kanji components restore the previous tab and fit small screens', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'mobile-chrome', 'Mobile-only kanji sheet.')
  await page.setViewportSize({ width: 320, height: 568 })
  await openFreshApp(page)
  await page.getByTestId('nav-kanji').click()
  await page.getByTestId('kanji-cell-語').scrollIntoViewIfNeeded()
  const pageScroll = await page.evaluate(() => window.scrollY)
  await page.getByTestId('kanji-cell-語').tap()
  await page.getByTestId('kanji-info-tab-composition').tap()
  await page.getByTestId('kanji-component-言').tap()
  await expect(page.getByTestId('kanji-info-char')).toHaveAttribute('data-character', '言')
  await expect(page.getByTestId('kanji-stack-path')).toContainText('語 → 言')
  await page.getByTestId('kanji-info-stack-back').tap()
  await expect(page.getByTestId('kanji-info-tab-composition')).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByTestId('kanji-composition-formula')).toContainText('→ 語')

  for (const viewport of [{ width: 320, height: 568 }, { width: 812, height: 375 }]) {
    await page.setViewportSize(viewport)
    await page.getByTestId('kanji-info-tab-words').tap()
    const card = page.getByTestId('kanji-info-card')
    await expect(card).toBeInViewport({ ratio: 1 })
    expect(await card.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
    expect(await page.getByTestId('kanji-info-body').evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
    await expect(page.getByTestId('kanji-info-close')).toBeInViewport()
    await expect(page.getByTestId('kanji-info-practice')).toBeInViewport()
  }
  await page.setViewportSize({ width: 320, height: 568 })
  await page.getByTestId('kanji-info-close').tap()
  await expect(page.getByTestId('kanji-info-card')).toHaveCount(0)
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(pageScroll)
})
