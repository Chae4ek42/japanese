import { test } from '@playwright/test'
import { expect, openFreshApp } from './helpers.js'

test('mobile word trainer has three recall actions and a compact header', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'mobile-chrome', 'Mobile layout and self-assessment.')
  await openFreshApp(page)
  await expect(page.getByTestId('nav-home')).toHaveText('Японский')
  await expect(page).toHaveTitle('Японский')
  await page.getByTestId('open-vocab-train').click()
  await expect(page.getByText('Шпаргалка:', { exact: false })).toHaveCount(0)
  await page.getByTestId('start-vocab').click()
  await expect(page.getByRole('heading', { name: 'Тренажёр слов' })).toBeHidden()
  await expect(page.getByTestId('vocab-practice-settings')).toBeVisible()
  await expect(page.locator('.vocab-mobile-answer-actions button')).toHaveText(['Помню', 'Не помню', 'Подсказка'])
  await expect(page.locator('.practice-topline')).toHaveCount(0)
  await expect(page.getByTestId('session-chips').locator('.info-tip')).toHaveCount(0)
  await expect(page.getByTestId('nav-train')).toBeInViewport()
  await page.screenshot({ path: testInfo.outputPath('compact-trainer.png'), scale: 'css' })

  const writing = page.getByTestId('vocab-current-writing')
  const first = await writing.innerText()
  await page.getByTestId('vocab-remember').dblclick({ delay: 40 })
  await expect(writing).not.toHaveText(first)
  await expect(page.getByTestId('session-chips').locator('.session-chip')).toHaveText(['1 карточка', /^100% чисто/, /^серия 1/])

  const second = await writing.innerText()
  await page.getByTestId('vocab-dont-know').tap()
  await expect(writing).not.toHaveText(second)
  await expect(page.getByTestId('session-chips').locator('.session-chip')).toHaveText(['2 карточки', /^50% чисто/, /^серия 0/])

  const third = await writing.innerText()
  await page.getByTestId('vocab-hint-button').tap()
  await expect(page.getByTestId('vocab-hint-panel')).toBeVisible()
  await expect(writing).toHaveText(third)
  await page.getByTestId('vocab-remember').tap()
  await expect(writing).not.toHaveText(third)
  await expect(page.getByTestId('session-chips').locator('.session-chip')).toHaveText(['3 карточки', /^33% чисто/, /^серия 0/])

  await page.setViewportSize({ width: 320, height: 568 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  for (const button of ['vocab-remember', 'vocab-dont-know', 'vocab-hint-button']) {
    await expect(page.getByTestId(button)).toBeInViewport()
  }
  await page.screenshot({ path: testInfo.outputPath('compact-trainer-small.png'), scale: 'css' })
  await page.getByTestId('vocab-practice-settings').tap()
  await expect(page.getByTestId('vocab-setup')).toBeVisible()
})

test('mobile header keeps account, backups and training sets accessible', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'mobile-chrome', 'Mobile header utilities.')
  await page.setViewportSize({ width: 320, height: 568 })
  await openFreshApp(page)
  await expect(page.getByTestId('export-backup')).toHaveCount(0)
  await expect(page.getByTestId('accounts-menu')).toHaveCount(0)
  await page.getByTestId('mobile-account-menu').tap()
  await expect(page.getByTestId('accounts-menu')).toContainText('Тест')
  const download = page.waitForEvent('download')
  await page.getByTestId('export-backup').tap()
  expect((await download).suggestedFilename()).toMatch(/\.json$/)
  await expect(page.getByTestId('mobile-account-panel')).toHaveCount(0)

  await page.getByTestId('mobile-account-menu').tap()
  const fileChooser = page.waitForEvent('filechooser')
  await page.getByTestId('import-backup').tap()
  await (await fileChooser).setFiles([])
  await page.getByTestId('training-sets-menu').tap()
  await expect(page.getByTestId('training-sets-panel')).toBeVisible()
  await page.getByTestId('nav-home').tap()
  await page.getByTestId('mobile-account-menu').tap()
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('mobile-account-panel')).toHaveCount(0)
  await expect(page.getByTestId('mobile-account-menu')).toBeFocused()
  await page.getByTestId('mobile-account-menu').tap()
  await page.getByTestId('accounts-menu').tap()
  await expect(page).toHaveURL(/\/accounts$/)
  await expect(page.getByTestId('account-current')).toContainText('Тест')
})

test('desktop retains the full header and word trainer controls', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'chromium', 'Desktop controls.')
  await openFreshApp(page)
  await expect(page.getByTestId('nav-home')).toHaveText('Японский')
  await expect(page.getByTestId('accounts-menu')).toBeVisible()
  await expect(page.getByTestId('export-backup')).toBeVisible()
  await expect(page.getByTestId('import-backup')).toBeVisible()
  await expect(page.getByTestId('mobile-account-menu')).toHaveCount(0)
  await page.getByTestId('open-vocab-train').click()
  await page.getByTestId('start-vocab').click()
  await expect(page.getByRole('heading', { name: 'Тренажёр слов' })).toBeVisible()
  await expect(page.getByTestId('vocab-answer-input')).toBeVisible()
  await expect(page.getByTestId('vocab-skip-next')).toBeVisible()
  await expect(page.getByTestId('vocab-remember')).toHaveCount(0)
})
